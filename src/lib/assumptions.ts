/** 입력값의 출처를 실행 기록에 옮겨 적기 위한 목록 */
export function collectSources(): string[] {
  const sources = FIELD_SPECS.flatMap((field) =>
    (field.sources ?? []).map((source) => `${source.label} | ${source.url}`),
  );
  return [...new Set(sources)];
}
